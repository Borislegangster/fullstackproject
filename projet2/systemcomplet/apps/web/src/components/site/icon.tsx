export const ICON_NAMES = Object.keys(ICONS).sort();

export function DynIcon({ name, className, fallback = true }: { name?: string | null; className?: string; fallback?: boolean }) {
  const Icon = (name && ICONS[name]) || (fallback ? Sparkles : null);
  if (!Icon) return null;
  return <Icon className={className ?? "h-6 w-6"} aria-hidden="true" />;
}
