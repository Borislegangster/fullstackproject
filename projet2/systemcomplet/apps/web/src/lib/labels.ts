export function tradeOptions(): { value: string; label: string }[] {
  return SUBCONTRACTING_TRADES.flatMap((g) => g.codes.map((code) => ({ value: code, label: optionLabel(code) })));
}

/** Métiers individuels de chantier sans corps d'état propre, jamais proposés aux sous-traitants.
 * Miroir de CREW_TRADES (backend/app/modules/subcontracting/trades.py, vérifié par tests/test_person_trades.py). */
export const CREW_TRADES: string[] = ["manoeuvre", "conduite_engins", "grutier", "chauffeur", "soudure", "topographie", "mecanique", "magasinier", "gardiennage", "nettoyage"];

/** Métier d'une personne (salarié, utilisateur, équipe) : corps de métier de la sous-traitance (mêmes codes) ou métier de chantier. */
export const PERSON_TRADES: { family: string; codes: string[] }[] = [...SUBCONTRACTING_TRADES, { family: "Métiers de chantier", codes: CREW_TRADES }];

/** Métiers des personnes en options de liste (filtres). */
export function personTradeOptions(): { value: string; label: string }[] {
  return PERSON_TRADES.flatMap((g) => g.codes.map((code) => ({ value: code, label: optionLabel(code) })));
}
